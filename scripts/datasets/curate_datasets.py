"""
Curate and Filter Datasets for Expera AI Training.

Features:
- Deduplication
- Language balancing
- Quality filtering
- Toxicity filtering
- Size filtering

Usage:
    python scripts/datasets/curate_datasets.py --input data/raw --output data/curated
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import random
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


@dataclass
class CurateConfig:
    """Configuration for dataset curation."""

    input_dir: Path
    output_dir: Path
    dedupe: bool = True
    quality_filter: bool = True
    toxicity_filter: bool = True
    min_length: int = 50
    max_length: int = 50000
    language_balance: bool = True
    target_languages: dict[str, int] = field(default_factory=dict)


class DatasetCurator:
    """Curates and filters datasets."""

    # Languages to file extensions
    EXT_TO_LANG = {
        ".py": "python",
        ".js": "javascript",
        ".ts": "typescript",
        ".jsx": "javascript",
        ".tsx": "typescript",
        ".rs": "rust",
        ".go": "go",
        ".java": "java",
        ".c": "c",
        ".cpp": "cpp",
        ".h": "c",
        ".hpp": "cpp",
        ".cs": "csharp",
        ".rb": "ruby",
        ".php": "php",
        ".swift": "swift",
        ".kt": "kotlin",
        ".scala": "scala",
        ".sql": "sql",
        ".sh": "bash",
        ".bash": "bash",
        ".zsh": "bash",
    }

    # Quality filter patterns
    BAD_PATTERNS = [
        r"\.gitignore",
        r"LICENSE",
        r"copyright",
        r"autogenerated",
        r"do not edit",
        r"ignore Errors",
        r"Mock",
        r"TODO.*implement",
        r"pass # noqa",
    ]

    # Toxicity patterns
    TOXICITY_PATTERNS = [
        r"hack.*hack",
        r"shit",
        r"fuck",
        r"damn",
        r"porn",
        r"nude",
    ]

    def __init__(self, config: CurateConfig):
        """Initialize curator."""
        self.config = config
        self.config.output_dir.mkdir(parents=True, exist_ok=True)
        self.hashes: set[str] = set()

    def detect_language(self, content: str, filename: str = "") -> str:
        """Detect programming language."""
        ext = Path(filename).suffix.lower() if filename else ""

        if ext in self.EXT_TO_LANG:
            return self.EXT_TO_LANG[ext]

        # Simple heuristics
        if re.search(r"^import\s+\w+", content, re.MULTILINE):
            if "from typing import" in content:
                return "python"
            if "console.log" in content or "document." in content:
                return "javascript"
            if "func " in content and "package " in content:
                return "go"
            if "fn " in content and "let " in content:
                return "rust"

        return "unknown"

    def compute_hash(self, content: str) -> str:
        """Compute content hash for deduplication."""
        return hashlib.md5(content.encode()).hexdigest()

    def check_quality(self, content: str) -> bool:
        """Check if content passes quality filters."""
        for pattern in self.BAD_PATTERNS:
            if re.search(pattern, content, re.IGNORECASE):
                return False
        return True

    def check_toxicity(self, content: str) -> bool:
        """Check for toxicity."""
        content_lower = content.lower()
        for pattern in self.TOXICITY_PATTERNS:
            if re.search(pattern, content_lower):
                return False
        return True

    def check_length(self, content: str) -> bool:
        """Check length constraints."""
        return self.config.min_length <= len(content) <= self.config.max_length

    def is_valid(self, record: dict) -> bool:
        """Check if record is valid."""
        content = record.get("content", record.get("code", record.get("text", "")))

        if not content:
            return False

        if not self.check_length(content):
            return False

        if self.config.quality_filter and not self.check_quality(content):
            return False

        if self.config.toxicity_filter and not self.check_toxicity(content):
            return False

        return True

    def deduplicate(self, record: dict) -> bool:
        """Check and add deduplication."""
        content = record.get("content", record.get("code", record.get("text", "")))
        if not content:
            return False

        h = self.compute_hash(content)
        if h in self.hashes:
            return False

        self.hashes.add(h)
        return True

    def curate_file(self, input_file: Path, output_file: Path) -> int:
        """Curate a single dataset file."""
        count = 0
        lang_counts = Counter()

        with open(input_file, "r", encoding="utf-8") as fin, \
             open(output_file, "w", encoding="utf-8") as fout:

            for line in fin:
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue

                # Check validity
                if self.config.quality_filter or self.config.toxicity_filter:
                    if not self.is_valid(record):
                        continue

                # Deduplication
                if self.config.dedupe:
                    if not self.deduplicate(record):
                        continue

                # Language detection
                content = record.get("content", record.get("code", record.get("text", "")))
                filename = record.get("filename", record.get("repo_name", ""))
                lang = self.detect_language(content, filename)

                if self.config.language_balance:
                    target = self.config.target_languages.get(lang, float("inf"))
                    if lang_counts[lang] >= target:
                        continue

                fout.write(line)
                count += 1
                lang_counts[lang] += 1

                if count % 10000 == 0:
                    logger.info(f"Processed {count} records ({dict(lang_counts)})")

        logger.info(f"Saved {count} records from {input_file.name}")
        return count

    def balance_languages(self, input_file: Path, output_file: Path) -> int:
        """Balance languages in dataset."""
        lang_records: dict[str, list[str]] = defaultdict(list)

        # Group by language
        with open(input_file, "r", encoding="utf-8") as f:
            for line in f:
                try:
                    record = json.loads(line)
                    content = record.get("content", record.get("code", record.get("text", "")))
                    lang = self.detect_language(content)
                    lang_records[lang].append(line)
                except json.JSONDecodeError:
                    continue

        # Sample equally
        min_count = min(len(recs) for recs in lang_records.values()) if lang_records else 0
        min_count = min(min_count, 10000)  # Cap at 10k

        count = 0
        with open(output_file, "w", encoding="utf-8") as f:
            for lang, records in lang_records.items():
                sampled = random.sample(records, min(min_count, len(records)))
                for line in sampled:
                    f.write(line)
                    count += 1

        logger.info(f"Balanced to {count} records")
        return count

    def compute_stats(self, input_file: Path) -> dict:
        """Compute dataset statistics."""
        stats = {
            "total": 0,
            "languages": Counter(),
            "lengths": [],
        }

        sizes = [0, 100, 500, 1000, 5000, 10000, 50000]
        length_buckets = {s: 0 for s in sizes}

        with open(input_file, "r", encoding="utf-8") as f:
            for line in f:
                try:
                    record = json.loads(line)
                    content = record.get("content", record.get("code", record.get("text", "")))

                    stats["total"] += 1
                    stats["languages"][self.detect_language(content)] += 1

                    length = len(content)
                    for s in sizes:
                        if length >= s:
                            length_buckets[s] += 1

                except json.JSONDecodeError:
                    continue

        stats["length_distribution"] = length_buckets
        return stats


def parse_args() -> argparse.Namespace:
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description="Curate datasets")

    parser.add_argument(
        "--input",
        type=str,
        required=True,
        help="Input directory with raw datasets",
    )

    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="Output directory for curated datasets",
    )

    parser.add_argument(
        "--dedupe",
        action="store_true",
        default=True,
        help="Enable deduplication",
    )

    parser.add_argument(
        "--no-dedupe",
        dest="dedupe",
        action="store_false",
        help="Disable deduplication",
    )

    parser.add_argument(
        "--quality-filter",
        action="store_true",
        default=True,
        help="Enable quality filter",
    )

    parser.add_argument(
        "--no-quality-filter",
        dest="quality_filter",
        action="store_false",
        help="Disable quality filter",
    )

    parser.add_argument(
        "--toxicity-filter",
        action="store_true",
        default=True,
        help="Enable toxicity filter",
    )

    parser.add_argument(
        "--min-length",
        type=int,
        default=50,
        help="Minimum content length",
    )

    parser.add_argument(
        "--max-length",
        type=int,
        default=50000,
        help="Maximum content length",
    )

    parser.add_argument(
        "--balance",
        action="store_true",
        default=False,
        help="Balance languages",
    )

    parser.add_argument(
        "--stats",
        action="store_true",
        default=False,
        help="Compute statistics only",
    )

    return parser.parse_args()


async def main() -> None:
    """Main function."""
    args = parse_args()

    input_dir = Path(args.input)
    output_dir = Path(args.output)

    config = CurateConfig(
        input_dir=input_dir,
        output_dir=output_dir,
        dedupe=args.dedupe,
        quality_filter=args.quality_filter,
        toxicity_filter=args.toxicity_filter,
        min_length=args.min_length,
        max_length=args.max_length,
        language_balance=args.balance,
    )

    curator = DatasetCurator(config)

    if args.stats:
        # Compute stats
        for f in input_dir.glob("*.jsonl"):
            logger.info(f"Stats for {f.name}:")
            stats = curator.compute_stats(f)
            print(json.dumps(stats, indent=2))
        return

    # Process files
    for f in input_dir.glob("*.jsonl"):
        output_file = output_dir / f.name
        curator.curate_file(f, output_file)

    logger.info("Curation complete!")


if __name__ == "__main__":
    import asyncio

    asyncio.run(main())